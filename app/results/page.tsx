import Link from "next/link";
import * as data from "@/lib/data";
import { INSTRUMENTS, isInstrumentKey } from "@/instruments/registry";
import { requirePartner } from "@/app/_lib/session";
import { DOMAIN_TITLES, parsePrivateResults } from "@/app/_lib/results";
import { Card, UnvalidatedLabel } from "@/app/_components/Card";
import { PageHeader } from "@/app/_components/PageHeader";
import { Waiting } from "@/app/_components/Waiting";
import { LinkButton } from "@/app/_components/Button";
import { ViewedButton } from "./ViewedButton";

function instrumentName(key: string): string {
  return isInstrumentKey(key) ? INSTRUMENTS[key].definition.name : key;
}

export default async function ResultsPage() {
  const user = await requirePartner();
  const run = await data.getLatestRun(user.couple.id);
  if (!run || run.status !== "complete") {
    return (
      <div className="space-y-6">
        <PageHeader title="Your results" />
        <Waiting title={run ? "Interpreting… this takes a few minutes." : "Your partner hasn't finished yet."}>
          <Link href="/waiting" className="underline">
            Waiting room
          </Link>
        </Waiting>
      </div>
    );
  }
  const row = await data.getPrivateResults(user.id, user.couple.id);
  const results = row ? parsePrivateResults(row.content) : null;
  if (!row || !results) {
    return (
      <div className="space-y-6">
        <PageHeader title="Your results" />
        <Waiting title="Your results are being prepared.">Check again in a moment.</Waiting>
      </div>
    );
  }
  const viewed = !!row.viewed_at;
  const flagged = [...results.flagged_domains].sort((x, y) => y.weight - x.weight);

  return (
    <div className="space-y-6">
      <PageHeader title="Your results, privately" lede="Only you can see this page. Your partner has their own. One plain sentence per instrument, with the cutoff named where one is published." />

      <Card>
        <h2 className="text-lg font-semibold">Instrument scores</h2>
        <ul className="mt-3 space-y-3">
          {results.sentences.map((s) => (
            <li key={s.instrument_key}>
              <p className="text-xs uppercase tracking-wide text-muted">
                {instrumentName(s.instrument_key)}
                {isInstrumentKey(s.instrument_key) && INSTRUMENTS[s.instrument_key].definition.unvalidated ? <UnvalidatedLabel /> : null}
              </p>
              <p>{s.sentence}</p>
            </li>
          ))}
        </ul>
        <p className="mt-3 text-xs text-muted">{results.generated_label}</p>
      </Card>

      {results.distress_note ? (
        <Card>
          <h2 className="text-lg font-semibold">A note on context</h2>
          <p className="mt-2">{results.distress_note}</p>
          <p className="mt-2 text-xs text-muted">generated by the interpreter; not validated.</p>
        </Card>
      ) : null}

      <Card>
        <h2 className="text-lg font-semibold">Domains that flagged</h2>
        {flagged.length === 0 ? (
          <p className="mt-2">No domain flagged. The brief will list what lines up; the written questions of the color layer are not needed.</p>
        ) : (
          <table className="mt-3 w-full text-sm">
            <thead>
              <tr>
                <th scope="col">Domain</th>
                <th scope="col">Weight</th>
                <th scope="col">Flags</th>
              </tr>
            </thead>
            <tbody>
              {flagged.map((d) => (
                <tr key={d.domain}>
                  <td>{DOMAIN_TITLES[d.domain]}</td>
                  <td>{d.weight}</td>
                  <td>{d.flag_count}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        <p className="mt-3 text-xs text-muted">Weights come from the flag rules in config/flag_rules.json; the list is the same for both of you.</p>
      </Card>

      <Card>
        <h2 className="text-lg font-semibold">Perception gaps about you</h2>
        {results.perception_gaps.length === 0 ? (
          <p className="mt-2">None of two points or more.</p>
        ) : (
          <ul className="mt-3 space-y-2 text-sm">
            {results.perception_gaps.map((g) => (
              <li key={`${g.instrument}:${g.item_ref}`}>
                <span className="font-medium">{g.descriptor}</span> ({instrumentName(g.instrument)}
                {g.instrument === "polarization" || g.unvalidated ? <UnvalidatedLabel /> : null}): you {g.self_value}, your partner {g.partner_value}, in {DOMAIN_TITLES[g.domain]}.
              </li>
            ))}
          </ul>
        )}
      </Card>

      <Card>
        {viewed ? (
          <div className="flex flex-wrap gap-3">
            {flagged.length > 0 ? <LinkButton href="/color">Go to the written questions</LinkButton> : <LinkButton href="/brief">Go to the brief</LinkButton>}
            <LinkButton href="/results/profile" variant="secondary">
              My individual profile
            </LinkButton>
          </div>
        ) : (
          <div className="space-y-2">
            <p className="text-sm text-muted">Take your time. The next steps unlock once you have read this page.</p>
            <ViewedButton />
          </div>
        )}
      </Card>
    </div>
  );
}
